"""External Enterprise Integrations API Endpoints (GitHub & Slack).

Allows testing, dispatching, and monitoring integration hooks.
"""

from typing import Any, Dict, Optional
from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel, Field

from backend.app.core.auth import UserProfile, UserRole, require_role
from backend.app.core.config import settings
from backend.app.integrations.github import github_client
from backend.app.integrations.slack import slack_dispatcher

router = APIRouter(prefix="/integrations", tags=["Enterprise Integrations (Slack & GitHub)"])


class TestSlackAlertRequest(BaseModel):
    incident_id: str = Field(default="inc_demo_01")
    title: str = Field(default="Connection Pool Starvation in Payment Gateway")
    severity: str = Field(default="CRITICAL")
    service: str = Field(default="payment-service")
    error_rate: float = Field(default=0.85)


class TestGitHubPRRequest(BaseModel):
    branch_name: str = Field(default="traceheal/fix-payment-service-pool")
    title: str = Field(default="fix(payment-service): increase max connections and add timeout")
    body: str = Field(default="Automated SRE Pull Request generated by TraceHeal")
    diff_patch: str = Field(default="--- a/config.py\n+++ b/config.py\n@@ -1,2 +1,2 @@\n-max_conns = 5\n+max_conns = 25\n")


@router.get("/status")
async def get_integrations_status():
    """Returns connectivity and configuration status for external webhooks and VCS."""
    return {
        "slack": {
            "configured": slack_dispatcher.is_configured,
            "webhook_target": "Configured (Slack Block Kit)" if slack_dispatcher.is_configured else "Unconfigured (Simulated Local Mode)",
        },
        "github": {
            "configured": github_client.is_configured,
            "target_repo": github_client.repo,
            "mode": "Remote Upstream REST v3" if github_client.is_configured else "Dry-Run Simulation Mode",
        },
    }


@router.post("/slack/test")
async def test_slack_alert(
    req: TestSlackAlertRequest,
    user: UserProfile = Depends(require_role(UserRole.SRE_OPERATOR)),
):
    """Dispatches a test Block Kit notification to Slack."""
    result = await slack_dispatcher.send_incident_alert(
        incident_id=req.incident_id,
        title=req.title,
        severity=req.severity,
        service=req.service,
        error_rate=req.error_rate,
    )
    return {"status": "SUCCESS", "dispatch_result": result}


@router.post("/github/test-pr")
async def test_github_pr(
    req: TestGitHubPRRequest,
    user: UserProfile = Depends(require_role(UserRole.SRE_OPERATOR)),
):
    """Dispatches or simulates a Pull Request creation."""
    result = await github_client.create_pull_request(
        branch_name=req.branch_name,
        title=req.title,
        body=req.body,
        diff_patch=req.diff_patch,
    )
    return {"status": "SUCCESS", "pull_request": result}
