import datetime
import uuid
from sqlalchemy import (
    BigInteger,
    Boolean,
    Column,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
)
from sqlalchemy.orm import relationship

from backend.app.db.session import Base


def generate_uuid() -> str:
    return str(uuid.uuid4())


def utc_now() -> datetime.datetime:
    return datetime.datetime.now(datetime.timezone.utc)


class Incident(Base):
    """Represents a microservice outage or performance degradation."""
    __tablename__ = "incidents"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    title = Column(String(255), nullable=False)
    description = Column(Text, nullable=True)
    status = Column(
        String(32),
        nullable=False,
        default="DETECTED",
        index=True
        # Values: DETECTED, INVESTIGATING, REPRODUCING, VERIFIED, REMEDIATED, RESOLVED, CLOSED
    )
    severity = Column(String(16), nullable=False, default="HIGH", index=True)
    suspect_service = Column(String(64), nullable=True, index=True)
    root_cause_summary = Column(Text, nullable=True)
    blast_radius_json = Column(Text, nullable=True)
    
    postmortem_markdown = Column(Text, nullable=True)
    pull_request_json = Column(Text, nullable=True)
    resolved_at = Column(DateTime(timezone=True), nullable=True)
    closed_at = Column(DateTime(timezone=True), nullable=True)

    created_at = Column(DateTime(timezone=True), default=utc_now, nullable=False)
    updated_at = Column(DateTime(timezone=True), default=utc_now, onupdate=utc_now, nullable=False)

    # Relationships
    spans = relationship("TelemetrySpan", back_populates="incident", cascade="all, delete-orphan", lazy="selectin")
    hypotheses = relationship("Hypothesis", back_populates="incident", cascade="all, delete-orphan", lazy="selectin")
    sandbox_runs = relationship("SandboxRun", back_populates="incident", cascade="all, delete-orphan", lazy="selectin")
    remediations = relationship("Remediation", back_populates="incident", cascade="all, delete-orphan", lazy="selectin")
    audit_events = relationship("AuditEvent", back_populates="incident", cascade="all, delete-orphan", lazy="selectin")


class TelemetrySpan(Base):
    """Stores distributed tracing spans ingested from OpenTelemetry."""
    __tablename__ = "telemetry_spans"
    __table_args__ = (
        Index("ix_spans_trace_start", "trace_id", "start_time_ns"),
    )

    id = Column(Integer, primary_key=True, autoincrement=True)
    incident_id = Column(String(36), ForeignKey("incidents.id", ondelete="CASCADE"), nullable=True, index=True)
    
    trace_id = Column(String(64), nullable=False, index=True)
    span_id = Column(String(32), nullable=False, index=True)
    parent_span_id = Column(String(32), nullable=True, index=True)
    
    service_name = Column(String(64), nullable=False, index=True)
    operation_name = Column(String(128), nullable=False)
    
    start_time_ns = Column(BigInteger, nullable=False)
    end_time_ns = Column(BigInteger, nullable=False)
    duration_ms = Column(Float, nullable=False)
    
    status_code = Column(String(16), nullable=False, default="UNSET", index=True)  # OK, ERROR, UNSET
    http_status_code = Column(Integer, nullable=True)
    error_message = Column(Text, nullable=True)
    
    attributes_json = Column(Text, nullable=True)
    events_json = Column(Text, nullable=True)
    created_at = Column(DateTime(timezone=True), default=utc_now, nullable=False)

    incident = relationship("Incident", back_populates="spans")


class Hypothesis(Base):
    """An evidence-based causal explanation generated by the RCA Agent."""
    __tablename__ = "hypotheses"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    incident_id = Column(String(36), ForeignKey("incidents.id", ondelete="CASCADE"), nullable=False, index=True)
    
    rank = Column(Integer, nullable=False, default=1)
    title = Column(String(255), nullable=False)
    description = Column(Text, nullable=False)
    suspect_service = Column(String(64), nullable=False)
    suspect_component = Column(String(128), nullable=True)
    proposed_cause = Column(Text, nullable=False)
    evidence_summary = Column(Text, nullable=True)
    reproduction_recipe_json = Column(Text, nullable=True)
    
    status = Column(
        String(32),
        nullable=False,
        default="PENDING",
        index=True
        # Values: PENDING, TESTING, VERIFIED, REFUTED
    )
    created_at = Column(DateTime(timezone=True), default=utc_now, nullable=False)

    incident = relationship("Incident", back_populates="hypotheses")
    sandbox_runs = relationship("SandboxRun", back_populates="hypothesis", cascade="all, delete-orphan")


class SandboxRun(Base):
    """An isolated execution run in a shadow process/container."""
    __tablename__ = "sandbox_runs"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    incident_id = Column(String(36), ForeignKey("incidents.id", ondelete="CASCADE"), nullable=False, index=True)
    hypothesis_id = Column(String(36), ForeignKey("hypotheses.id", ondelete="CASCADE"), nullable=True, index=True)
    
    service_name = Column(String(64), nullable=False)
    sandbox_type = Column(String(32), nullable=False, default="PROCESS")  # PROCESS, CONTAINER
    port = Column(Integer, nullable=False)
    
    status = Column(
        String(32),
        nullable=False,
        default="PENDING",
        index=True
        # Values: PENDING, RUNNING, SUCCESS, FAILED, ABORTED
    )
    exit_code = Column(Integer, nullable=True)
    stdout_log = Column(Text, nullable=True)
    stderr_log = Column(Text, nullable=True)
    
    reproduction_verified = Column(Boolean, default=False, nullable=False)
    reproduction_signature = Column(Text, nullable=True)
    
    created_at = Column(DateTime(timezone=True), default=utc_now, nullable=False)
    finished_at = Column(DateTime(timezone=True), nullable=True)

    incident = relationship("Incident", back_populates="sandbox_runs")
    hypothesis = relationship("Hypothesis", back_populates="sandbox_runs")


class Remediation(Base):
    """A proposed and tested fix for an incident."""
    __tablename__ = "remediations"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    incident_id = Column(String(36), ForeignKey("incidents.id", ondelete="CASCADE"), nullable=False, index=True)
    hypothesis_id = Column(String(36), ForeignKey("hypotheses.id", ondelete="CASCADE"), nullable=True, index=True)
    
    patch_type = Column(String(32), nullable=False, default="CONFIG")  # CONFIG, CODE, CANARY_ROLLBACK
    target_service = Column(String(64), nullable=False)
    diff_content = Column(Text, nullable=False)
    
    policy_check_status = Column(String(32), nullable=False, default="PENDING")  # PENDING, PASSED, REJECTED
    policy_violations_json = Column(Text, nullable=True)

    validation_status = Column(
        String(32),
        nullable=False,
        default="PENDING",
        index=True
        # Values: PENDING, VALIDATED, FAILED
    )
    validation_details_json = Column(Text, nullable=True)
    
    approval_status = Column(
        String(32),
        nullable=False,
        default="PENDING_APPROVAL",
        index=True
        # Values: PENDING_APPROVAL, APPROVED, REJECTED
    )
    applied_at = Column(DateTime(timezone=True), nullable=True)
    rollback_diff = Column(Text, nullable=True)
    created_at = Column(DateTime(timezone=True), default=utc_now, nullable=False)

    incident = relationship("Incident", back_populates="remediations")
    hypothesis = relationship("Hypothesis")


class AuditEvent(Base):
    """Immutable audit trail of all actions and state transitions."""
    __tablename__ = "audit_events"

    id = Column(Integer, primary_key=True, autoincrement=True)
    incident_id = Column(String(36), ForeignKey("incidents.id", ondelete="CASCADE"), nullable=True, index=True)
    
    event_type = Column(String(64), nullable=False, index=True)
    actor = Column(String(64), nullable=False, default="SYSTEM")
    details_json = Column(Text, nullable=True)
    
    created_at = Column(DateTime(timezone=True), default=utc_now, nullable=False)

    incident = relationship("Incident", back_populates="audit_events")
